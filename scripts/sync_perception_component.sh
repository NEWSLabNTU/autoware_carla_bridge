#!/usr/bin/env bash
# Derive acb_launch's copy of autoware_launch's tier4_perception_component.launch.xml.
#
# The copy exists for one change: upstream hard-codes
#   <arg name="traffic_light_recognition/fusion_only" value="false"/>
# inside its include of tier4_perception_launch/perception.launch.xml, and an <include> of
# the component cannot override it. fusion_only drops the camera branch of traffic light
# recognition (camera_info relay, map-based detector, classifier) and keeps fusion, the
# arbiter and the crosswalk estimator -- which acb needs, because acb publishes the signal
# state from CARLA on external/traffic_signals (carla-scenario-bridge roadmap 015). Here
# it becomes a launch argument, default false as upstream.
#
# Second change (issue 026): the component includes acb_launch's copy of
# tier4_perception_launch's perception.launch.xml, which gates object recognition
# (detection, tracking, prediction, or the empty-objects publisher) on an
# `object_recognition` argument, default true. With it false the rest still runs --
# obstacle segmentation, the occupancy grid, traffic light fusion -- which planning and the
# diagnostic graph need while acb publishes ground-truth objects in recognition's place.
# The comparison is case-blind: carla_simulator passes an $(eval), which yields True/False.
#
#   scripts/sync_perception_component.sh          regenerate the copy from the installed upstream
#   scripts/sync_perception_component.sh --check  exit 1 if the copy differs from what it would regenerate
#
# Run --check after an Autoware upgrade; regenerate if it fails.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
upstream="${AUTOWARE_LAUNCH_SHARE:-/opt/autoware/1.5.0/share/autoware_launch}/launch/components/tier4_perception_component.launch.xml"
copy="$here/src/acb_launch/launch/components/tier4_perception_component.launch.xml"
up_perception="${TIER4_PERCEPTION_LAUNCH_SHARE:-/opt/autoware/1.5.0/share/tier4_perception_launch}/launch/perception.launch.xml"
perception_copy="$here/src/acb_launch/launch/components/perception.launch.xml"
up_include='<include file="$(find-pkg-share tier4_perception_launch)/launch/perception.launch.xml">'
grp_pipeline='<group unless="$(var use_empty_dynamic_object_publisher)">'
grp_empty='<group if="$(var use_empty_dynamic_object_publisher)">'
[ -f "$up_perception" ] || { echo "no upstream perception launch at $up_perception"; exit 2; }
[ "$(grep -cF "$up_include" "$upstream")" = 1 ] || {
    echo "upstream component no longer includes perception.launch.xml exactly once; revisit this copy"; exit 2; }
for g in "$grp_pipeline" "$grp_empty"; do [ "$(grep -cF "$g" "$up_perception")" = 1 ] || {
    echo "upstream perception.launch.xml no longer has '$g' exactly once; revisit this copy"; exit 2; }; done
hardcoded='<arg name="traffic_light_recognition/fusion_only" value="false"/>'
[ -f "$upstream" ] || { echo "no upstream component at $upstream"; exit 2; }
[ "$(grep -cF "$hardcoded" "$upstream")" = 1 ] || {
    echo "upstream no longer hard-codes fusion_only exactly once; revisit this copy"; exit 2; }

generate() {
    sed \
        -e "s|<include file=\"\$(find-pkg-share tier4_perception_launch)/launch/perception.launch.xml\">|<include file=\"\$(find-pkg-share acb_launch)/launch/components/perception.launch.xml\">\n    <arg name=\"object_recognition\" value=\"\$(var object_recognition)\"/>|" \
        -e "s|$hardcoded|<arg name=\"traffic_light_recognition/fusion_only\" value=\"\$(var traffic_light_recognition/fusion_only)\"/>|" \
        -e "0,/<launch>/s|<launch>|<launch>\n  <!-- GENERATED by acb scripts/sync_perception_component.sh from autoware_launch's\n       tier4_perception_component.launch.xml; do not edit by hand. Only change:\n       traffic_light_recognition/fusion_only is an argument instead of hard-coded false,\n       and the include is acb_launch's perception.launch.xml with object_recognition. -->\n  <arg name=\"object_recognition\" default=\"true\" description=\"launch object recognition; false when another publisher (acb ground truth) provides objects\"/>\n  <arg name=\"traffic_light_recognition/fusion_only\" default=\"false\" description=\"skip the camera branch of traffic light recognition; keep fusion, arbiter and crosswalk estimator\"/>|" \
        "$upstream"
}

gen_perception() {
    sed \
        -e "s|<group unless=\"\$(var use_empty_dynamic_object_publisher)\">|<group if=\"\$(eval \&quot;'\$(var object_recognition)'.lower() == 'true' and '\$(var use_empty_dynamic_object_publisher)'.lower() != 'true'\&quot;)\">|" \
        -e "s|<group if=\"\$(var use_empty_dynamic_object_publisher)\">|<group if=\"\$(eval \&quot;'\$(var object_recognition)'.lower() == 'true' and '\$(var use_empty_dynamic_object_publisher)'.lower() == 'true'\&quot;)\">|" \
        -e "0,/<launch>/s|<launch>|<launch>\n  <!-- GENERATED by acb scripts/sync_perception_component.sh from tier4_perception_launch's\n       perception.launch.xml; do not edit by hand. Only change: object recognition is gated\n       on object_recognition (issue 026). -->\n  <arg name=\"object_recognition\" default=\"true\" description=\"launch detection, tracking and prediction (or the empty-objects publisher)\"/>|" \
        "$up_perception"
}

if [ "${1:-}" = "--check" ]; then
    rc=0
    diff -q <(generate) "$copy" >/dev/null || { echo "perception component copy is out of date with $upstream"; rc=1; }
    diff -q <(gen_perception) "$perception_copy" >/dev/null || { echo "perception.launch.xml copy is out of date with $up_perception"; rc=1; }
    [ $rc = 0 ] && echo "perception component copies match upstream" || echo "run scripts/sync_perception_component.sh"
    exit $rc
else
    generate > "$copy"; echo "wrote $copy"
    gen_perception > "$perception_copy"; echo "wrote $perception_copy"
fi
